name = "Gabriel"
age = 19
height = 183

# daję literę 'f' przed cudzysłowem, dzięki czemu mogę wrzucać zmienne prosto w klamry {} zamiast sklejać tekst plusami
print(f"My name is {name}.")
print(f"I am {age} years old, and my height is {height} cm.")
print(f"In 6 years I will be {age + 6} years old.") # w klamrach mogę też od razu robić działania matematyczne